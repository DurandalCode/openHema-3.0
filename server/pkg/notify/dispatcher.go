// Package notify — диспетчер асинхронной отправки писем-уведомлений
// (спека 0042). В отличие от pkg/mail.Sender, который отправляет письмо
// синхронно по требованию вызывающего (служебные письма учётки — сброс
// пароля, подтверждение адреса), Dispatcher кладёт письмо в очередь и
// возвращает управление немедленно: доменная операция (постановка пула,
// подтверждение оплаты) не ждёт доставки почты и не откатывается при её
// сбое (FR-27, FR-28). Домен модуля-источника знает только «отправить
// уведомление» — конкретный канал (SMTP/лог) остаётся за pkg/mail.
package notify

import (
	"context"
	"log/slog"

	"github.com/hema/server/pkg/mail"
)

// Dispatcher — буферизованная очередь писем с одним фоновым воркером.
//
//   - Enqueue никогда не блокирует вызывающего: при заполненном буфере
//     сообщение отбрасывается, событие фиксируется в журнале (FR-28) —
//     обычный HTTP-запрос (постановка пула с десятком бойцов) не должен
//     ждать почтового воркера.
//   - Ошибка Sender.Send на одном письме не останавливает воркер: он не
//     ретраит и не паникует, просто пишет ошибку в журнал и берёт
//     следующее сообщение из очереди (FR-27).
type Dispatcher struct {
	ch     chan mail.Message
	sender mail.Sender
	log    *slog.Logger
	done   chan struct{}
}

// New создаёт диспетчер и запускает фоновую горутину-воркер, читающую из
// очереди и отправляющую письма через sender. bufferSize — ёмкость
// очереди; при её исчерпании Enqueue отбрасывает новые сообщения, не
// блокируя вызывающего.
func New(sender mail.Sender, log *slog.Logger, bufferSize int) *Dispatcher {
	d := &Dispatcher{
		ch:     make(chan mail.Message, bufferSize),
		sender: sender,
		log:    log,
		done:   make(chan struct{}),
	}
	go d.run()
	return d
}

// Enqueue кладёт письмо в очередь на асинхронную отправку. Никогда не
// блокирует вызывающего: при заполненном буфере сообщение отбрасывается с
// предупреждением в журнал вместо ожидания места.
func (d *Dispatcher) Enqueue(m mail.Message) {
	select {
	case d.ch <- m:
	default:
		d.log.Warn("notify: queue full, dropping message", "to", m.To, "subject", m.Subject)
	}
}

// Close закрывает очередь на приём новых писем и дожидается, пока воркер
// обработает всё, что уже было в очереди на момент вызова (дренаж),
// прежде чем вернуться. После Close вызывать Enqueue нельзя — как и любая
// запись в закрытый Go-канал, она приведёт к панике.
func (d *Dispatcher) Close() {
	close(d.ch)
	<-d.done
}

// run — тело фонового воркера: один воркер, последовательная обработка
// (никакой параллельной отправки — иначе логировать порядок и дренаж при
// Close было бы сложнее без выгоды: почтовая нагрузка этой фичи не требует
// параллелизма, см. plan.md «Риски и границы»).
func (d *Dispatcher) run() {
	defer close(d.done)
	for m := range d.ch {
		if err := d.sender.Send(context.Background(), m); err != nil {
			d.log.Error("notify: send failed", "to", m.To, "subject", m.Subject, "error", err)
		}
	}
}

/**
 * tournamentErrorMessage — переводит отказ сохранения профиля турнира по
 * HTTP-статусу, а не по тексту (spec 0029, обзор п.3): `res.error` от BFF —
 * английская строка Go-домена (`tournament: invalid input`) либо технический
 * текст сети/сервера, пользователю она не показывается (AC-9). 400 может
 * означать и пустое название, и битый диапазон дат — обе причины клиент
 * ловит заранее (`validateTournamentDraft`, FR-11/FR-12), поэтому
 * формулировка сознательно перечисляет обе, а не выбирает одну наугад.
 */
export function tournamentErrorMessage(_error: string, status: number): string {
  if (status === 400) {
    return "Проверьте название и даты: название обязательно, а окончание не может быть раньше начала";
  }
  if (status === 401 || status === 403) {
    return "Недостаточно прав";
  }
  return "Не удалось сохранить профиль турнира. Попробуйте ещё раз позже.";
}

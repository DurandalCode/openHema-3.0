/**
 * tournamentErrorMessage — переводит отказ сохранения профиля турнира по
 * HTTP-статусу, а не по тексту (spec 0029, обзор п.3): `res.error` от BFF —
 * английская строка Go-домена (`tournament: invalid input`) либо технический
 * текст сети/сервера, пользователю она не показывается (AC-9). 400 может
 * означать пустое название, битый диапазон дат, невалидную ссылку на
 * регламент (FR-20/AC-15) или некорректный взнос (FR-21/AC-16) — все четыре
 * клиент ловит заранее (`validateTournamentDraft`), но это сообщение
 * остаётся последней линией (race, будущий баг обхода пре-валидации),
 * поэтому перечисляет все причины, а не выбирает одну наугад.
 */
export function tournamentErrorMessage(_error: string, status: number): string {
  if (status === 400) {
    return "Проверьте название, даты, ссылку на регламент и взнос: название обязательно, окончание не может быть раньше начала, ссылка на регламент — полной (http/https), а взнос — неотрицательным числом";
  }
  if (status === 401 || status === 403) {
    return "Недостаточно прав";
  }
  return "Не удалось сохранить профиль турнира. Попробуйте ещё раз позже.";
}

/**
 * uploadFileErrorMessage — переводит отказ загрузки/удаления файла профиля
 * турнира по HTTP-статусу (спека 0042, T39, FR-32): 400 — тип или размер
 * не подошли (отбраковка либо на BFF, T36, либо сервером по бинарной
 * сигнатуре, NFR-9 — в обоих случаях причина одна и та же для пользователя),
 * 409 — файловое хранилище не настроено (`ErrStorageUnavailable`, NFR-4),
 * 401/403 — недостаточно прав. Локальная пре-проверка типа/размера в
 * `file-or-link-field.tsx` ловит большинство случаев раньше запроса — этот
 * текст остаётся последней линией.
 */
export function uploadFileErrorMessage(status: number): string {
  if (status === 400) {
    return "Файл не подходит по типу или размеру. Проверьте требования рядом с полем.";
  }
  if (status === 401 || status === 403) {
    return "Недостаточно прав";
  }
  if (status === 409) {
    return "Файловое хранилище недоступно. Попробуйте позже или используйте ссылку.";
  }
  return "Не удалось выполнить действие с файлом. Попробуйте ещё раз позже.";
}

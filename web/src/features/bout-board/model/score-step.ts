/**
 * applyScoreStep — клиентская арифметика быстрых шагов счёта (спека 0013,
 * FR-2a): кнопки `±1/±2/±3/±5` у каждого бойца меняют его счёт на дельту
 * поверх текущего значения из доски. Результат ограничен снизу нулём — шаг
 * `−N`, уводящий в минус, клампится к 0 (AC-2a). Абсолютный результат затем
 * шлётся на сервер одним запросом (`ScoreCurrentBout`), сама дельта на
 * сервер не уходит (plan: «±N — UX, не модель»).
 */
export function applyScoreStep(current: number, delta: number): number {
  return Math.max(0, current + delta);
}

/**
 * presetErrorMessage — переводит отказ сервера при переименовании/удалении
 * пресета (спека 0029, FR-21/AC-13) в русский текст по HTTP-статусу, а не по
 * содержимому строки (тот же приём, что `registrationErrorMessage` из 0028):
 * типизированный код ошибки потребовал бы правки `/proto`, а имена пресетов
 * уникальны на индексе `uq_presets_name` (0020) — единственная содержательная
 * причина отказа здесь и есть конфликт имени (409). Прочие статусы (в т.ч.
 * отсутствующий — сетевая ошибка) сводятся к одной общей формулировке: сырая
 * строка сервера пользователю не показывается.
 */

const NAME_CONFLICT_MESSAGE = "Пресет с таким именем уже есть — выберите другое";
const GENERIC_MESSAGE = "Не удалось выполнить действие. Попробуйте ещё раз.";

export function presetErrorMessage(_error: string, status?: number): string {
  return status === 409 ? NAME_CONFLICT_MESSAGE : GENERIC_MESSAGE;
}

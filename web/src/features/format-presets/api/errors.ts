/**
 * presetErrorMessage — переводит отказ сервера в операциях над пресетами
 * (переименование/удаление/сохранение/применение — спека 0029 FR-21/AC-13,
 * 0031 FR-27) в русский текст по HTTP-статусу, а не по содержимому строки
 * (тот же приём, что `registrationErrorMessage` из 0028): типизированный код
 * ошибки потребовал бы правки `/proto`. 409 у разных операций означает разное
 * — конфликт имени пресета (переименование/удаление/сохранение) либо уже
 * тронутая схема номинации (применение формата, 0020 FR-13/FR-14) — поэтому
 * `context` выбирает нужную формулировку; по умолчанию — конфликт имени
 * (существующие вызовы из переименования/удаления). Прочие статусы (в т.ч.
 * отсутствующий — сетевая ошибка) сводятся к одной общей формулировке: сырая
 * строка сервера пользователю не показывается.
 */

export type PresetErrorContext = "name" | "apply";

const NAME_CONFLICT_MESSAGE = "Пресет с таким именем уже есть — выберите другое";
const SCHEMA_TOUCHED_MESSAGE =
  "Схема номинации уже тронута — формат можно применить только к пустой схеме";
const GENERIC_MESSAGE = "Не удалось выполнить действие. Попробуйте ещё раз.";

export function presetErrorMessage(
  _error: string,
  status?: number,
  context: PresetErrorContext = "name",
): string {
  if (status !== 409) return GENERIC_MESSAGE;
  return context === "apply" ? SCHEMA_TOUCHED_MESSAGE : NAME_CONFLICT_MESSAGE;
}
